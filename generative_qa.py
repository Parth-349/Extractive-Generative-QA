"""
Generative Question Answering module using Ollama or Groq.
"""

from dataclasses import dataclass
from typing import Optional, Tuple, List, Set
import time
import re
import requests
from openai import OpenAI, APIConnectionError, APITimeoutError, APIError

from config import (
    GENERATIVE_MODEL_NAME,
    OLLAMA_BASE_URL,
    OLLAMA_REQUEST_TIMEOUT,
    GROQ_BASE_URL,
    GROQ_MODEL_NAME,
    DEFAULT_TEMPERATURE,
    DEFAULT_MAX_TOKENS,
)


@dataclass
class GenerativeResult:
    """
    Generative QA inference result.

    Attributes:
        answer: Final user-facing answer text generated by the model.
        latency_s: Wall-clock generation latency in seconds.
        success: Whether generation completed successfully without errors.
        error: Error message if success is False.
        model_name: Model identifier used for generation.
        reasoning: Deprecated / kept for backward compatibility (always None; reasoning traces are not exposed).
    """
    answer: str
    latency_s: float
    success: bool
    error: Optional[str] = None
    model_name: str = GENERATIVE_MODEL_NAME
    reasoning: Optional[str] = None


def normalize_model_tag(tag: str) -> Set[str]:
    """
    Generates normalized forms of an Ollama model tag for exact comparison.
    Handles variations with and without the ':latest' suffix.
    Examples:
        'qwen3:8b'       -> {'qwen3:8b'}
        'llama3'         -> {'llama3', 'llama3:latest'}
        'llama3:latest'  -> {'llama3', 'llama3:latest'}
    """
    cleaned = tag.strip().lower()
    if not cleaned:
        return set()
    forms = {cleaned}
    if cleaned.endswith(":latest"):
        forms.add(cleaned[:-7])
    elif ":" not in cleaned:
        forms.add(f"{cleaned}:latest")
    return forms


def check_exact_model_match(target_model: str, available_models: List[str]) -> bool:
    """
    Performs exact normalized tag matching against available Ollama model tags.
    Prevents broad substring matches (e.g. 'qwen' matching 'qwen3:8b' or 'qwen3:8b-coder').
    """
    target_forms = normalize_model_tag(target_model)
    for model_tag in available_models:
        model_forms = normalize_model_tag(model_tag)
        if target_forms & model_forms:
            return True
    return False


class GenerativeQAModel:
    """Wrapper for Ollama or Groq generative QA via the OpenAI-compatible API."""

    def __init__(
        self,
        base_url: Optional[str] = None,
        model_name: Optional[str] = None,
        timeout: int = OLLAMA_REQUEST_TIMEOUT,
        provider: str = "ollama",
        api_key: Optional[str] = None,
    ):
        self.provider = provider.strip().lower()
        if self.provider not in {"ollama", "groq"}:
            raise ValueError("provider must be either 'ollama' or 'groq'.")
        if self.provider == "groq" and (not api_key or not api_key.strip()):
            raise ValueError("An API key is required when using the Groq provider.")

        default_base_url = GROQ_BASE_URL if self.provider == "groq" else OLLAMA_BASE_URL
        default_model_name = GROQ_MODEL_NAME if self.provider == "groq" else GENERATIVE_MODEL_NAME
        self.base_url = (base_url if base_url is not None else default_base_url).rstrip("/")
        self.model_name = model_name if model_name is not None else default_model_name
        self.timeout = timeout
        self.client = OpenAI(
            base_url=self.base_url,
            api_key=api_key if self.provider == "groq" else "ollama",
            timeout=float(self.timeout),
        )

    def check_connection(self) -> Tuple[bool, str, List[str]]:
        """
        Checks provider connectivity and verifies if the requested model exists.
        Returns (is_connected, status_message, list_of_available_models).
        """
        if self.provider == "groq":
            try:
                response = self.client.models.list()
                models = [model.id for model in response.data if model.id]
                if self.model_name in models:
                    return True, f"Groq is reachable. Model '{self.model_name}' is available.", models
                return (
                    True,
                    f"Groq is reachable, but model '{self.model_name}' was not found. "
                    f"Available models: {', '.join(models) if models else 'None'}.",
                    models,
                )
            except APITimeoutError:
                return False, f"Groq connection check timed out after {self.timeout} seconds.", []
            except APIConnectionError:
                return False, f"Cannot connect to Groq at {self.base_url}.", []
            except APIError as e:
                return False, f"Groq connection check failed: {str(e)}", []
            except Exception as e:
                return False, f"Groq connection check failed: {str(e)}", []

        root_url = self.base_url.replace("/v1", "")
        try:
            resp = requests.get(f"{root_url}/api/tags", timeout=4)
            if resp.status_code == 200:
                data = resp.json()
                models = [m.get("name", "") for m in data.get("models", []) if m.get("name")]
                # Exact normalized tag matching
                if check_exact_model_match(self.model_name, models):
                    return True, f"Ollama is running. Model '{self.model_name}' is available.", models
                else:
                    return (
                        True,
                        f"Ollama is running, but model '{self.model_name}' was not found. "
                        f"Available models: {', '.join(models) if models else 'None'}. "
                        f"Run `ollama pull {self.model_name}` to download it.",
                        models,
                    )
            return False, f"Ollama returned HTTP status {resp.status_code}.", []
        except requests.exceptions.ConnectionError:
            return (
                False,
                f"Cannot connect to Ollama at {root_url}. "
                "Ensure Ollama is running (`ollama serve` or open the Ollama desktop app).",
                [],
            )
        except Exception as e:
            return False, f"Ollama connection check failed: {str(e)}", []

    def answer_question(
        self,
        passage: str,
        question: str,
        temperature: float = DEFAULT_TEMPERATURE,
        max_tokens: int = DEFAULT_MAX_TOKENS,
    ) -> GenerativeResult:
        """
        Generates a concise, factual answer grounded strictly in the passage.
        Returns only the final user-facing answer without internal reasoning traces.
        """
        if not passage or not passage.strip():
            return GenerativeResult(
                answer="",
                latency_s=0.0,
                success=False,
                error="The context passage is empty.",
                model_name=self.model_name,
            )

        if not question or not question.strip():
            return GenerativeResult(
                answer="",
                latency_s=0.0,
                success=False,
                error="The question is empty.",
                model_name=self.model_name,
            )

        system_instruction = (
            "You are a factual question-answering assistant. "
            "You will be given a context passage and a question. "
            "Answer the question using ONLY facts directly mentioned in the context. "
            "If the answer cannot be determined from the passage, state: "
            "'The provided passage does not contain this information.' "
            "Be direct, concise, and do not explain your thought process or internal reasoning."
        )

        user_content = (
            f"Context Passage:\n{passage.strip()}\n\n"
            f"Question:\n{question.strip()}\n\n"
            f"Provide a concise, direct answer based strictly on the context above."
        )

        start_time = time.perf_counter()

        try:
            response = self.client.chat.completions.create(
                model=self.model_name,
                messages=[
                    {"role": "system", "content": system_instruction},
                    {"role": "user", "content": user_content},
                ],
                temperature=temperature,
                max_tokens=max_tokens,
            )
            latency = time.perf_counter() - start_time

            choice = response.choices[0]
            message = choice.message
            raw_content = message.content or ""

            # Strip any internal <think> blocks if generated in content so only final answer remains
            clean_answer = re.sub(r"<think>.*?</think>", "", raw_content, flags=re.DOTALL).strip()

            if not clean_answer:
                clean_answer = "No response generated by the model."

            return GenerativeResult(
                answer=clean_answer,
                latency_s=latency,
                success=True,
                error=None,
                model_name=self.model_name,
                reasoning=None,
            )

        except APITimeoutError:
            latency = time.perf_counter() - start_time
            return GenerativeResult(
                answer="",
                latency_s=latency,
                success=False,
                error=f"{self.provider.capitalize()} request timed out after {self.timeout} seconds.",
                model_name=self.model_name,
            )
        except APIConnectionError:
            latency = time.perf_counter() - start_time
            error = (
                f"Connection failed: Could not reach Ollama at {self.base_url}. "
                "Please ensure Ollama is running (`ollama serve`)."
                if self.provider == "ollama"
                else f"Connection failed: Could not reach Groq at {self.base_url}."
            )
            return GenerativeResult(
                answer="",
                latency_s=latency,
                success=False,
                error=error,
                model_name=self.model_name,
            )
        except APIError as e:
            latency = time.perf_counter() - start_time
            return GenerativeResult(
                answer="",
                latency_s=latency,
                success=False,
                error=f"{self.provider.capitalize()} API error: {str(e)}",
                model_name=self.model_name,
            )
        except Exception as e:
            latency = time.perf_counter() - start_time
            return GenerativeResult(
                answer="",
                latency_s=latency,
                success=False,
                error=f"Unexpected error: {str(e)}",
                model_name=self.model_name,
            )
